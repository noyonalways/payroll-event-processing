// Generates packages/ui/src/index.ts (the barrel) and exports.json (the subpath
// map) by resolving every beUI slug to the file that actually holds its exports.
//
// The slug does not always match a filename: `not-found-glitch` lives in
// not-found/glitch.tsx, and four button slugs share motion/button/index.tsx.
// Matching is by resolution, not by convention, so a rename upstream surfaces as
// a hard error here instead of a silent missing export.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const UI = process.argv[2] ?? ".";
const MANIFEST = process.argv[3] ?? ".beui-manifest.json";

const manifest = JSON.parse(await readFile(MANIFEST, "utf8"));
const src = path.join(UI, "src");

/** Resolve a slug to the file that holds its exports.
 *
 * beUI ships three shapes:
 *   1. one flat file  -> components/motion/tabs.tsx
 *   2. a folder with an index.tsx -> components/motion/table/index.tsx
 *   3. a folder of peers named after the slug -> components/motion/not-found/glitch.tsx
 * ...and two folders group several slugs (motion/button, agents/loading-states).
 */
const slugFile = new Map();
const missing = [];
for (const [slug, dir] of Object.entries(manifest.dirs)) {
  const inDir = (name) => manifest.files.includes(path.posix.join(dir, name));
  const candidates = [
    `${dir}/${slug}.tsx`,
    `${dir}/${slug}.ts`,
    `${dir}/index.tsx`,
    `${dir}/index.ts`,
  ];
  // Shape 3: `not-found-glitch` -> not-found/glitch.tsx, last path segment.
  const tail = slug.split("-").pop();
  candidates.push(`${dir}/${tail}.tsx`, `${dir}/${tail}.ts`);

  const chosen = candidates.find((c) => manifest.files.includes(c));
  if (!chosen) {
    missing.push({ slug, dir });
    continue;
  }
  slugFile.set(slug, chosen);
}
if (missing.length) {
  throw new Error(
    "unresolved slugs:\n" + missing.map((m) => `  ${m.slug} (${m.dir})`).join("\n")
  );
}

// Several slugs may share one entry file (loading-states x3). Keep one subpath.
const byEntry = new Map();
for (const [slug, file] of slugFile) {
  const list = byEntry.get(file) ?? [];
  list.push(slug);
  byEntry.set(file, list);
}

const exportLine = (file) => {
  const rel = "./" + file.replace(/\.tsx?$/, "");
  return `export * from ${JSON.stringify(rel)};`;
};

// Two components can legitimately export the same helper name (knockout-wheel
// and knockout-bracket both ship `Team`/`Match`/`ROUNDS`). A barrel of bare
// `export *` would make those ambiguous, so any file that collides is expanded
// into explicit named re-exports that drop the shared fixture names.
const namedExports = new Map();
for (const file of byEntry.keys()) {
  const srcText = await readFile(path.join(src, file), "utf8");
  const names = new Set();
  const re =
    /^export\s+(?:type\s+|interface\s+|function\s+|const\s+|let\s+|class\s+)([A-Za-z0-9_$]+)/gm;
  for (const m of srcText.matchAll(re)) names.add(m[1]);
  namedExports.set(file, [...names]);
}

const countByName = new Map();
for (const names of namedExports.values()) {
  for (const n of names) countByName.set(n, (countByName.get(n) ?? 0) + 1);
}
const collided = new Set(
  [...countByName].filter(([, c]) => c > 1).map(([n]) => n)
);

const exportLines = (file) => {
  const rel = "./" + file.replace(/\.tsx?$/, "");
  const names = namedExports.get(file).filter((n) => !collided.has(n));
  const dropped = namedExports.get(file).filter((n) => collided.has(n));
  if (!dropped.length) return [`export * from ${JSON.stringify(rel)};`];
  // `export {}` re-exports types and values alike, so one line covers both.
  return [
    `export { ${names.join(", ")} } from ${JSON.stringify(rel)};`,
    `// Shared fixture names kept out of the barrel (a sibling exports them too): ${dropped.join(", ")}`,
  ];
};

// Barrel in registry order so the file reads top-down like beui.dev's index.
const barrel = [];
for (const [file, slugs] of byEntry) {
  barrel.push(...exportLines(file), `// ^ ${slugs.join(", ")}`);
}

await writeFile(
  path.join(src, "index.ts"),
  [
    "// AUTO-GENERATED by scripts/build-beui-exports.mjs — do not edit by hand.",
    "// Every beUI component vendored from https://beui.dev/r/registry.json.",
    "// Each source file also has its own subpath, e.g. `@repo/ui/chat-app`.",
    "",
    "// App-level chrome that is deliberately not part of the beUI tree.",
    'export { Button, buttonVariants, type ButtonProps } from "./app/button";',
    "",
    ...barrel,
    "",
  ].join("\n"),
  "utf8"
);

// Subpath map: @repo/ui/<slug> -> the slug's entry file, plus direct file paths.
const exportsMap = {
  ".": {
    source: "./src/index.ts",
    types: "./dist/index.d.ts",
    import: "./dist/index.js",
    default: "./src/index.ts",
  },
};
for (const [file, slugs] of byEntry) {
  // Keep the real extension: flat components are .tsx, but a folder entry may
  // be a .ts util (e.g. tooltip). Dist mirrors the source extension as .js.
  const base = file.replace(/\.tsx?$/, "");
  const entry = {
    source: `./src/${file}`,
    types: `./dist/${base}.d.ts`,
    import: `./dist/${base}.js`,
    default: `./src/${file}`,
  };
  for (const slug of slugs) exportsMap[`./${slug}`] = entry;
}
// App chrome subpath.
exportsMap["./app-button"] = {
  source: "./src/app/button.tsx",
  types: "./dist/app/button.d.ts",
  import: "./dist/app/button.js",
  default: "./src/app/button.tsx",
};
// `button` is not a registry slug — beUI ships button-base/-stateful/-magnetic/
// -metallic as four separate items that share one folder. Expose the folder
// index as `@repo/ui/button` so a caller can import the whole button family
// from one stable path, and keep the four registry slugs working too.
const buttonEntry = [...byEntry.keys()].find((f) =>
  /\/(button\/index)\.tsx$/.test(f) || /(^|\/)button\/index\.tsx$/.test(f)
);
if (buttonEntry) {
  const base = buttonEntry.replace(/\.tsx?$/, "");
  exportsMap["./button"] = {
    source: `./src/${buttonEntry}`,
    types: `./dist/${base}.d.ts`,
    import: `./dist/${base}.js`,
    default: `./src/${buttonEntry}`,
  };
}

// Escape hatches for deep imports (internal helpers, unlisted peers).
exportsMap["./lib/*"] = {
  source: "./src/lib/*",
  types: "./dist/lib/*.d.ts",
  import: "./dist/lib/*.js",
  default: "./src/lib/*",
};
exportsMap["./components/*"] = {
  source: "./src/components/*",
  types: "./dist/components/*.d.ts",
  import: "./dist/components/*.js",
  default: "./src/components/*",
};

await writeFile(path.join(UI, "exports.json"), JSON.stringify(exportsMap, null, 2), "utf8");
console.log(`barrel entries: ${byEntry.size}, subpaths: ${Object.keys(exportsMap).length - 1}`);
